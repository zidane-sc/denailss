export function getDesignBySlug(slug: string) {
  return GALLERY_DESIGNS.find((design) => design.slug === slug);
}

export function getRelatedDesigns(design: GalleryDesign, limit = 4) {
  return GALLERY_DESIGNS.filter(
    (d) =>
      d.id !== design.id &&
      (d.style === design.style || d.occasion === design.occasion || d.color === design.color)
  ).slice(0, limit);
}
